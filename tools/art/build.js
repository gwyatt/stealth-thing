// Generates the creature SVGs into assets/art/creatures. Run: node tools/art/build.js
import { writeFileSync, mkdirSync } from 'node:fs';
import { svg } from './lib.js';
import { ART as A1 } from './act1.js';
import { ART as A2 } from './act2.js';
import { ART as A3 } from './act3.js';

const all = { ...A1, ...A2, ...A3 };
const out = new URL('../../assets/art/creatures/', import.meta.url);
mkdirSync(out, { recursive: true });
for (const [id, a] of Object.entries(all)) {
  writeFileSync(new URL(`${id}.svg`, out), svg(a.w, a.h, a.pal, a.body, { lightFrom: a.lightFrom }));
}
const manifest = Object.fromEntries(Object.entries(all).map(([id, a]) => [id, [a.w, a.h]]));
writeFileSync(new URL('../../src/ui/art/manifest.js', import.meta.url), `// Generated by tools/art/build.js — creature art dimensions [width, height].\nexport const CREATURE_SIZE = ${JSON.stringify(manifest, null, 0).replace(/],/g, '],\n  ').replace('{', '{\n  ').replace(/}$/, ',\n}')};\n`);
console.log(`wrote ${Object.keys(all).length} creatures`);

// Scenes
import * as scenes from './scenes.js';
const sceneOut = new URL('../../assets/art/scenes/', import.meta.url);
mkdirSync(sceneOut, { recursive: true });
for (const name of ['crypt', 'warrens', 'throne', 'title', 'bonfire', 'vellum']) {
  writeFileSync(new URL(`${name}.svg`, sceneOut), scenes[name]());
}
console.log('wrote 6 scenes');
